    #[test]
    fn is_committable_matches_ts_matrix() {
        let style = AnnotationStyle::default();
        let build = |tool: Tool, points: Vec<Point>, text: Option<&str>| Annotation {
            id: "id".to_string(),
            tool,
            style: style.clone(),
            points,
            text: text.map(str::to_string),
        };

        assert!(build(Tool::Rectangle, corners(0.0, 0.0, 1.0, 1.0), None).is_committable());
        assert!(!build(Tool::Rectangle, corners(0.0, 0.0, 0.0, 1.0), None).is_committable());
        assert!(!build(Tool::Ellipse, corners(0.0, 0.0, 1.0, 0.0), None).is_committable());
        assert!(!build(Tool::Mosaic, corners(0.0, 0.0, 0.0, 0.0), None).is_committable());
        // Fewer than two corners cannot form a rect.
        assert!(!build(Tool::Rectangle, vec![point(1.0, 1.0)], None).is_committable());

        assert!(build(Tool::Arrow, vec![point(0.0, 0.0), point(1.0, 1.0)], None).is_committable());
        assert!(!build(Tool::Arrow, vec![point(2.0, 3.0), point(2.0, 3.0)], None).is_committable());

        assert!(build(Tool::Pen, vec![point(0.0, 0.0), point(1.0, 1.0)], None).is_committable());
        assert!(!build(Tool::Pen, vec![point(0.0, 0.0)], None).is_committable());

        assert!(build(Tool::Text, vec![point(1.0, 1.0)], Some("hi")).is_committable());
        assert!(!build(Tool::Text, vec![point(1.0, 1.0)], Some("   ")).is_committable());
        assert!(!build(Tool::Text, vec![point(1.0, 1.0)], None).is_committable());

        assert!(build(Tool::Translation, corners(0.0, 0.0, 2.0, 2.0), Some("hi")).is_committable());
        assert!(
            !build(Tool::Translation, corners(0.0, 0.0, 0.0, 2.0), Some("hi")).is_committable()
        );
        assert!(!build(Tool::Translation, corners(0.0, 0.0, 2.0, 2.0), Some(" ")).is_committable());
    }

