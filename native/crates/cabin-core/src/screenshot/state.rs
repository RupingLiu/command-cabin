    #[test]
    fn text_prompt_commit_and_cancel() {
        let selected = reducer(
            &reducer(&initial_state(), set_selection()),
            ScreenshotAction::ToolSelected { tool: Tool::Text },
        );
        let start = ScreenshotAction::AnnotationStarted {
            point: point(30.0, 42.0),
        };
        // A click (drag distance <= 3) opens the prompt.
        let prompted = reducer(
            &reducer(&selected, start),
            ScreenshotAction::TextPromptStarted {
                from: point(30.0, 42.0),
                to: point(32.0, 43.0),
            },
        );
        let prompt = prompted.text_prompt.as_ref().expect("prompt");
        assert_eq!(prompt.point, point(32.0, 43.0));
        assert_eq!(prompt.value, "");
        assert_eq!(prompted.draft_annotation, None);
        assert_eq!(prompted.annotation_anchor, None);

        let committed = reducer(
            &prompted,
            ScreenshotAction::CommitText {
                value: "  Note  ".to_string(),
            },
        );
        assert_eq!(committed.text_prompt, None);
        assert_eq!(committed.annotations.len(), 1);
        assert!(committed.redo_annotations.is_empty());
        let text = &committed.annotations[0];
        assert_eq!(text.tool, Tool::Text);
        assert_eq!(text.text.as_deref(), Some("Note"));
        assert_eq!(text.points, vec![point(32.0, 43.0)]);
        assert_eq!(text.style, prompted.style);
        assert!(!text.id.is_empty());

        // Blank input is discarded, matching commitPendingTextAnnotation.
        let blank = reducer(
            &prompted,
            ScreenshotAction::CommitText {
                value: "   ".to_string(),
            },
        );
        assert_eq!(blank.annotations.len(), 0);
        assert_eq!(blank.text_prompt, None);

        // CommitText without a prompt is a no-op.
        assert_eq!(
            reducer(
                &selected,
                ScreenshotAction::CommitText {
                    value: "x".to_string()
                }
            ),
            selected
        );
    }

